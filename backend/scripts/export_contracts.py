"""Export the API contract to shared/contracts/ from the FastAPI app (single source of truth).

    python scripts/export_contracts.py          # write files
    python scripts/export_contracts.py --check  # exit 1 if committed files are stale (used in CI)

Outputs:
    shared/contracts/openapi.yaml           full OpenAPI 3.1 document
    shared/contracts/schemas/<Name>.json    one JSON Schema per component (refs -> sibling files)
"""

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import yaml

BACKEND = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND))

from app.core.config import Settings  # noqa: E402
from app.main import create_app  # noqa: E402

CONTRACTS = BACKEND.parent / "shared" / "contracts"
SCHEMA_ID_BASE = "https://mathmind.local/contracts/schemas/"


def _rewrite_refs(node: Any) -> Any:
    if isinstance(node, dict):
        out = {}
        for k, v in node.items():
            if k == "$ref" and isinstance(v, str) and v.startswith("#/components/schemas/"):
                out[k] = v.removeprefix("#/components/schemas/") + ".json"
            else:
                out[k] = _rewrite_refs(v)
        return out
    if isinstance(node, list):
        return [_rewrite_refs(v) for v in node]
    return node


def build() -> dict[str, str]:
    """Returns {relative_path: file_content}."""
    app = create_app(Settings(database_url="sqlite://", seed_on_startup=False))
    spec = app.openapi()
    files: dict[str, str] = {
        "openapi.yaml": "# GENERATED by backend/scripts/export_contracts.py — do not edit by hand.\n"
        + yaml.safe_dump(spec, sort_keys=False, allow_unicode=True, width=120),
    }
    for name, schema in spec.get("components", {}).get("schemas", {}).items():
        doc = {
            "$schema": "https://json-schema.org/draft/2020-12/schema",
            "$id": f"{SCHEMA_ID_BASE}{name}.json",
            **_rewrite_refs(schema),
        }
        files[f"schemas/{name}.json"] = json.dumps(doc, indent=2, ensure_ascii=False) + "\n"
    return files


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files = build()

    stale = []
    for rel, content in files.items():
        path = CONTRACTS / rel
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            stale.append(rel)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8", newline="\n")
    expected = set(files)
    orphans = [
        p.relative_to(CONTRACTS).as_posix()
        for p in (CONTRACTS / "schemas").glob("*.json")
        if p.relative_to(CONTRACTS).as_posix() not in expected
    ]
    if not args.check:
        for rel in orphans:
            (CONTRACTS / rel).unlink()

    if args.check and (stale or orphans):
        print("Contract is stale. Run: python scripts/export_contracts.py", file=sys.stderr)
        for rel in stale + orphans:
            print(f"  - {rel}", file=sys.stderr)
        return 1
    print(
        f"{'checked' if args.check else 'wrote'} {len(files)} contract files"
        + (f" ({len(stale)} changed, {len(orphans)} removed)" if not args.check else "")
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
